// Captures d'écran de l'appli en mode démo (usage : node tests/shots.mjs [dossier] [dark|light])
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const out = process.argv[2] || 'shots';
const scheme = process.argv[3] || 'dark';
const URL = process.env.URL || 'http://localhost:4173/';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, colorScheme: scheme, locale: 'fr-FR', serviceWorkers: 'block' });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto(URL);
if (process.env.LANG_APP) { await page.evaluate((l) => localStorage.setItem('gb:lang', l), process.env.LANG_APP); await page.reload(); }
await page.locator('.welcome .btn.ghost').click();
await page.waitForTimeout(900);
const shot = async (name, full = true) => {
  await page.waitForTimeout(900);
  await page.screenshot({ path: `${out}/${scheme}-${name}.png`, fullPage: full });
};
await shot('1-suivi');
await page.locator('.nav button').nth(1).click();
await shot('2-depenses');
await page.locator('.nav button').nth(3).click();
await shot('3-epargne');
await page.locator('.nav button').nth(4).click();
await shot('4-bilan-1mois');
await page.locator('.chip').nth(3).click();
await shot('5-bilan-6mois');
await page.getByRole('tab').nth(1).click();
await shot('6-charges');
await page.locator('.nav .plus').click();
await shot('7-ajout', false);
await page.locator('.sheet-close').click();
await page.waitForTimeout(400);
await page.locator('.topbar .round-btn').click();
await shot('8-reglages', false);
await page.locator('.icobtn').first().click();
await shot('9-icones', false);
console.log(errors.length ? 'ERREURS:\n' + errors.join('\n') : 'aucune erreur console');
await browser.close();
